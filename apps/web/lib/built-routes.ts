/** その route の画面がもうあるか（:id は実際の値でも合う） */
export function isBuilt(route: string): boolean {
  const p = route.split("?")[0]!.replace(/\/+$/, "") || "/";
  return BUILT_ROUTES.some((b) => {
    if (b === p) return true;
    const bs = b.split("/");
    const ps = p.split("/");
    return bs.length === ps.length && bs.every((s, i) => s.startsWith(":") || s === ps[i]);
  });
}
