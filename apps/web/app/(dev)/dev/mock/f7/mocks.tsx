import type { Theme } from "@/lib/theme";
import type { MockEntry } from "./types";
import { NOTICE_RENDERS } from "./states/notice";
import { OVERVIEW_MOCKS } from "./states/overview";
import { SAVED_MOCKS } from "./states/saved";
import { STOPPED_MOCKS } from "./states/stopped";

export type { MockEntry } from "./types";

const BODIES: Record<string, MockEntry["render"]> = {
  ...NOTICE_RENDERS,
  ...Object.fromEntries([...OVERVIEW_MOCKS, ...SAVED_MOCKS, ...STOPPED_MOCKS].map((m) => [m.id, m.render])),
};

function renderOf(id: string): MockEntry["render"] {
  return (theme) => {
    const body = BODIES[id];
    if (!body) throw new Error(`下絵の中身が無い状態：${id}`);
    return body(theme);
  };
}

