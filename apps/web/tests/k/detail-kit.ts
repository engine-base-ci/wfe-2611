//   汎用の道具（押せない物の確かめ・キャンバスとの突き合わせ・測る道具）は kit.ts（K-257 が運ぶ）に在り、ここから読み直して渡す
//   （K-227・K-228 と前からの試験は、今までどおり detail-kit から読めばよい）
//   ・詳細の本文と右のパネルの操作要素の一覧（detailRows）：前からの「操作要素の漏れ」の試験（K62-UI-000・K63-UI-020）が、
//     K-60・K-62・K-63 の表に足して読む（帯と小窓の中の操作要素は K-63・K-62 の表が持つ）
//   テストはチケットを作る人が書き、実装する人は変えない（D-128.125）
import type { SpecRow } from "../_lib/row";

export * from "./kit";

// ---------------------------------------------------------------- 詳細の本文と右のパネルの操作要素（K-226）
/** まだ使えない操作（押せない形で出す・D-145.9）の名前。本文の道具の帯（14 個）は K-571 で詳細から無くなった（読む形には帯を出さない。道具は直すとき K-567 が出す）。
 *  パネルのタブ「やり取り」は K-392 で押せる形になったので外した（今は空・後ろの葉の操作は DETAIL_LATER） */
export const DETAIL_INERT: readonly string[] = [];

/** 後ろの葉が本物にする操作（K-446 複製・K-458 ほかの操作・K-449 版と差分・K-452 子を足す・つながりを足す）。
 *  段 5 の W0（K-431）が 1 回だけ DETAIL_INERT から外した：在るかだけを見て、押せないかは見ない（押せるようになっても赤にならない） */
export const DETAIL_LATER = ["複製", "ほかの操作", "版と差分", "子を足す", "つながりを足す"] as const;

/** 後ろの葉が詳細に足す操作要素の名前の形（K226-UI-025 の「一覧に無い操作要素」の確かめが、これに当たる名前は漏れと数えない）。
 *  段 5 の W0（K-431）が 1 回だけ足した：本文を書く・並べ替える・消す・足す・つなぐ・外す・親を決める・テスト仕様・版と差分の操作。
 *  後ろの葉（K-443〜K-452・K-458）はこの一覧を替えない（この形に当たる名前だけを足す） */
export const DETAIL_MAY_APPEAR: readonly RegExp[] = [
  /を書く$/,
  /^書き終える$/,
  /^やめる$/,
  /を並べ替える$/,
  /を消す$/,
  /^＋ 見出しを足す/,
  /^親チケットを決める$/,
  /^親を外す$/,
  /^親：/,
  /^期限を変える$/,
  /^型を選ぶ/,
  /^業務の型/,
  /^つなぐ$/,
  /を外す$/,
  /^＋ 項目を足す$/,
  /^項目を足す$/,
  /^抜けを点検する$/,
  /^AI の案を出す$/,
  /^直す$/,
  /^本文を直す$/, // 本文を見たまま直す入口（K-447・K-571 の BodySlot の中。K226-UI-025 の漏れに数えない）
  /^使う$/,
  /^版 \d+/,
  /^子を足す$/,
  /^つながりを足す$/,
  // 閉じた形の区画（テスト仕様・子とつながり）の「開く」（見出しの行に件数と置く・K-450・K-452）
  /^開く$/,
  /を開く$/,
];
export const isMayAppear = (name: string): boolean => DETAIL_MAY_APPEAR.some((re) => re.test(name));

const asRow = (role: string, name: string): SpecRow => ({
  id: "K226-UI-025",
  role,
  name,
  item: `（${role}）「${name}」`,
  expect: "詳細の本文と右のパネルの操作要素（K-226）",
});

/** 詳細の本文と右のパネルに置く操作要素。sectionLabels は前の形の本文の目次のリンクの名前（K-571 で目次は無くなったので、空でよい。前からの呼び方が渡しても余分に通すだけ）。me は見ている人の名前 */
export function detailRows(sectionLabels: string[], me = "高本"): SpecRow[] {
  const buttons = [
    "番号をコピー",
    ...DETAIL_INERT,
    ...DETAIL_LATER,
    "項目",
    "やり取り", // K-392：パネルのタブ「やり取り」は押せる（読んでいない数が 0 のときの名前）
    `${me}のAI`,
    "期限を変える",
    "パネルを閉じる",
    "パネルを開く",
    "実行の記録をすべて見る",
  ];
  return [...buttons.map((n) => asRow("button", n)), ...sectionLabels.map((n) => asRow("link", n))];
}
