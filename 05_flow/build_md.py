# -*- coding: utf-8 -*-
"""flow.json から MD を生成（三層出力の3層目・Git diff 用）。手で書かない。"""
import json, subprocess, os
F=json.load(open('flow.json',encoding='utf-8'))
ACTS={a['id']:a for p in F['backbone'] for a in p['acts']}
SCR={s['id']:s for s in F['screens']}
ROLE={r['id']:r for r in F['roles']}
L=[]
def w(s=""): L.append(s)

w("# Kaname — 使ってもらい方の設計")
w()
w("作成 2026-09-08 ／ **この文書は `flow.json` から自動生成している。手で書き換えない。**")
w("再生成: `python3 05_flow/build_flow.py && python3 05_flow/build_views.py && python3 05_flow/build_md.py`")
w()
w("> **画面から始めるな。行為から導け。**")
w("> 正本: `.claude/rules/common/screen-derivation.md` ／ スキル: `ux-flow-design`")
w()
w(f"役割 {len(F['roles'])} ／ 用事 {len(F['jobs'])} ／ 行為 {len(ACTS)} ／ オブジェクト {len(F['objects'])} ／ 画面 {len(F['screens'])} ／ 最初の一周 {len(F['walking_skeleton'])} 手")
w()
w("---")
w()
w("## ① 役割 × 用事")
w()
w("### 役割（肩書ではなく状況で書く）")
w()
w("| ID | 役割 | どういう人か | 頻度 |")
w("|---|---|---|---|")
for r in F['roles']: w(f"| {r['id']} | **{r['name']}** | {r['desc']} | {r['frequency']} |")
w()
w("### 用事（Jobs to be Done）")
w()
w("| ID | 〜したい | 誰の | いつ | いま何が起きているか（痛み） |")
w("|---|---|---|---|---|")
for j in F['jobs']: w(f"| {j['id']} | **{j['statement']}** | {' '.join(j['roles'])} | {j['when']} | {j['pain']} |")
w()
w("---")
w()
w("## ② 行為の背骨")
w()
w("フェーズは**頻度**で切っている。機能では切っていない。")
w()
w("### 最初の一周（walking skeleton）")
w()
w("```")
w("\n → ".join(f"{a} {ACTS[a]['act']}" for a in F['walking_skeleton']))
w("```")
w()
w("**ここが通らない製品は、機能が何個あっても使われない。**")
w()
for p in F['backbone']:
    w(f"### {p['phase']}")
    w()
    w("| ID | 行為 | 誰が | 頻度 | 用事 | 画面 |")
    w("|---|---|---|---|---|---|")
    for a in p['acts']:
        sc=", ".join(s.replace('new:','') for s in F['act_to_screen'].get(a['id'],[]))
        rel=" 【段階2】" if a['release']=='v2' else ""
        w(f"| {a['id']} | {a['act']}{rel} | {' '.join(a['roles'])} | {a['frequency']} | {' '.join(a['jobs'])} | {sc} |")
    w()
w("---")
w()
w("## ③ オブジェクト（OOUX）")
w()
w("| オブジェクト | 何か | 関係するもの |")
w("|---|---|---|")
for o in F['objects']: w(f"| **{o['name']}** | {o['desc']} | {' / '.join(o['relates_to'])} |")
w()
w("---")
w()
w("## ③b サービスブループリント")
w()
auto=sum(1 for v in F['blueprint'].values() if v['auto']!='—')
w(f"**{auto}/{len(F['blueprint'])}件（{round(auto/len(F['blueprint'])*100)}%）に自動側がある。** 関門は `03_architecture/choke-points.json` の C1〜C8。")
w()
for p in F['backbone']:
    w(f"### {p['phase']}")
    w()
    w("| ID | 人がすること | 画面 | 自動側がすること | 裏で動くもの | 関門 |")
    w("|---|---|---|---|---|---|")
    for a in p['acts']:
        b=F['blueprint'][a['id']]
        w(f"| {a['id']} | {b['human']} | {b['screen']} | {b['auto']} | {b['backstage']} | {' '.join(b['choke_points'])} |")
    w()
w("---")
w()
w("## ④ 画面の導出（双方向）")
w()
w("**担う行為が空の画面は 0 件。** `purpose` は画面を作る前に書いている。")
w()
w("| 画面ID | 画面名 | 担う行為 | この画面で何をするか | 主アクション | 段階 |")
w("|---|---|---|---|---|---|")
for s in F['screens']:
    w(f"| `{s['id']}` | {s['name']} | {' '.join(s['acts'])} | {s['purpose']} | {s['primary_action']} | {'段階2' if s['release']=='v2' else '段階1'} |")
w()
w("---")
w()
w("## ⑤ 導線")
w()
w("### 役割ごとの主ナビ")
w()
w("| 役割 | 項目数 | 主ナビ |")
w("|---|---|---|")
for rid, ss in F['navigation']['by_role'].items():
    w(f"| {rid} {ROLE[rid]['name']} | {len(ss)} | {' / '.join(SCR[x]['name'] for x in ss)} |")
w()
w("### 画面ごとの第2ナビ")
w()
import collections
dup=sum(1 for _,c in collections.Counter(tuple(x['label'] for x in v) for v in F['navigation']['sub_by_screen'].values()).items() if c>1)
w(f"第2ナビが同一の画面の組：**{dup} 組**（0でなければ規約違反）")
w()
w("| 画面 | 第2ナビ |")
w("|---|---|")
for k,v in F['navigation']['sub_by_screen'].items(): w(f"| `{k}` | {' ｜ '.join(x['label']+'（'+x['desc']+'）' for x in v)} |")
w()
w("---")
w()
w("## ⑥ 機械ゲート")
w()
os.chdir('..')
g1=subprocess.run(["python3","scripts/ci/flow_gate.py","--flow","05_flow/flow.json","--choke","03_architecture/choke-points.json"],capture_output=True,text=True).stdout.strip()
g9=subprocess.run(["python3","scripts/ci/flow_gate.py","--flow","05_flow/flow.json","--mocks","06_mockup/v1","--choke","03_architecture/choke-points.json"],capture_output=True,text=True).stdout.strip()
w("### flow.json 単体（G1〜G8・G10）")
w()
w("```"); w(g1); w("```")
w()
w("### 既存モックとの照合（G9）── ui-mockup への作業指示")
w()
w("```"); w(g9); w("```")
w()
open('05_flow/使ってもらい方.md','w',encoding='utf-8').write("\n".join(L)+"\n")
print("使ってもらい方.md 生成:", len(L), "行")
